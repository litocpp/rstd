"""Generate Unicode tables from the pinned UCD; --ucd-dir uses an offline copy."""

import argparse
import hashlib
import pathlib
import subprocess
import urllib.request


VERSION = "18.0.0"
SOURCES = {
    "DerivedCoreProperties.txt": "09c928886a178fcafd93c29e4bd59073a058e5a100b716d425cb563ab50f68c9",
    "extracted/DerivedGeneralCategory.txt": "d6b151d2d40ee9b1876d26f417980f45ffae47b6055ccf7203cb31f07a030f94",
    "PropList.txt": "f438f532e8737bb8a2702126cdf9c4af5e357c58c7acf9d9eb2fc7c1a1d955d6",
}
ROOT = pathlib.Path(__file__).resolve().parents[1]
TARGET = ROOT / "src/core/src/unicode.cppm"


def read_source(name, directory):
    if directory is not None:
        data = (directory / name).read_bytes()
    else:
        url = f"https://www.unicode.org/Public/{VERSION}/ucd/{name}"
        with urllib.request.urlopen(url, timeout=30) as response:
            data = response.read()
    if hashlib.sha256(data).hexdigest() != SOURCES[name]:
        raise ValueError(f"{name}: does not match the pinned Unicode {VERSION} data")
    return data.decode("utf-8")


def property_ranges(source, properties):
    ranges = []
    for line in source.splitlines():
        body = line.split("#", 1)[0].strip()
        if not body:
            continue
        fields = [field.strip() for field in body.split(";")]
        if fields[1] not in properties:
            continue
        bounds = fields[0].split("..")
        first, last = int(bounds[0], 16), int(bounds[-1], 16)
        if not 0 <= first <= last <= 0x10FFFF:
            raise ValueError(f"Invalid code point range: {fields[0]}")
        if last < 0x80:
            continue
        ranges.append((max(first, 0x80), last))
    merged = []
    for first, last in sorted(ranges):
        if merged and first <= merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], max(merged[-1][1], last))
        else:
            merged.append((first, last))
    if not merged:
        raise ValueError(f"No ranges found for {properties}")
    return merged


def generate(directory):
    sources = {name: read_source(name, directory) for name in SOURCES}
    lines = [
        f"// Generated by tools/generate-unicode.py; Unicode {VERSION}.",
        f"// Source: https://www.unicode.org/Public/{VERSION}/ucd/",
        "// Unicode data copyright 1991-2026 Unicode, Inc.; see LICENSE-UNICODE.",
        "export module rstd.core:unicode;",
        "import rstd.basic;",
        "namespace rstd::unicode {",
        "inline constexpr unsigned char version[3] { " + VERSION.replace(".", ", ") + " };",
        "struct Range { char32_t first, last; };",
        "template<size_t N>",
        "constexpr auto contains(const Range (&ranges)[N], char32_t value) noexcept -> bool {",
        "    size_t lo = 0, hi = N;",
        "    while (lo < hi) {",
        "        auto mid = lo + (hi - lo) / 2;",
        "        if (value < ranges[mid].first) hi = mid;",
        "        else if (value > ranges[mid].last) lo = mid + 1;",
        "        else return true;",
        "    }",
        "    return false;",
        "}",
    ]
    for name, source, properties in [
        ("alphabetic", "DerivedCoreProperties.txt", {"Alphabetic"}),
        ("letter", "extracted/DerivedGeneralCategory.txt", {"Lu", "Ll", "Lt", "Lm", "Lo"}),
        ("numeric", "extracted/DerivedGeneralCategory.txt", {"Nd", "Nl", "No"}),
        ("whitespace", "PropList.txt", {"White_Space"}),
    ]:
        ranges = property_ranges(sources[source], properties)
        lines.append(f"inline constexpr Range {name}_ranges[] {{")
        lines.extend(f"    {{ 0x{first:x}, 0x{last:x} }}," for first, last in ranges)
        lines.extend([
            "};",
            f"constexpr auto {name}(char32_t value) noexcept -> bool {{",
            f"    return contains({name}_ranges, value);",
            "}",
        ])
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ucd-dir", type=pathlib.Path)
    parser.add_argument("--clang-format", default="clang-format")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    formatted = subprocess.run(
        [args.clang_format, f"--assume-filename={TARGET}"],
        input=generate(args.ucd_dir), text=True, capture_output=True, check=True,
    ).stdout
    if args.check:
        if TARGET.read_text(encoding="utf-8") != formatted:
            raise SystemExit(f"{TARGET}: generated data is out of date")
    else:
        TARGET.write_text(formatted, encoding="utf-8")


if __name__ == "__main__":
    main()
